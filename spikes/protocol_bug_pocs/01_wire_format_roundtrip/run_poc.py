"""POC: isolates ONLY the `Protocol` + `ProtocolParser` encode/decode round trip
from the real ignite_qpid_protocol goal (Layer 1 - no Ignite, no Qpid, no Maven
project setup asked of the model at all) and objectively grades it by actually
compiling and running the generated Java against a fixed, deterministic test
driver (Main.java, written here - not generated), not by re-asking the model
to judge its own output.

Found live, 3 separate times this session (a-3, attribution-fix-validation-5,
attribution-fix-validation-7): the model gets the encode/decode round trip
wrong on attempt 1 at roughly the same rate every time - a 3-byte dataLength
field has no matching ByteBuffer primitive (put/putShort/putInt are 1/2/4
bytes), so the model has to hand-roll byte-shifting arithmetic and gets the
symmetry between encode() and decode() subtly wrong.

Also varies the field width (3 bytes, matching the real goal, vs. 5 bytes) to
directly test whether this is specific to "3 bytes" or a general property of
"non-standard byte width requiring hand-rolled bit-shifting" - the real
question behind "if the protocol definition changes, does this still hold."

Run: .venv/bin/python spikes/protocol_bug_pocs/01_wire_format_roundtrip/run_poc.py [--trials N] [--widths 3 5]
Requires `mvn` on PATH (already required by the real eval harness for this goal).
"""
import argparse
import asyncio
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))

from kriya.config import load_config  # noqa: E402
from kriya.core.llm import LLMClient  # noqa: E402

MODEL = "qwen3-coder:30b"
BASE_URL = "http://localhost:11434/v1"
TEMPERATURE = 0.2
MVN_TIMEOUT_SECONDS = 120

SYSTEM_PROMPT = (
    "You are an expert Java developer. Follow the requirements exactly and "
    "respond in exactly the format requested - no extra commentary."
)

POM_XML = """<project xmlns="http://maven.apache.org/POM/4.0.0">
  <modelVersion>4.0.0</modelVersion>
  <groupId>com.example</groupId>
  <artifactId>wire-format-poc</artifactId>
  <version>1.0-SNAPSHOT</version>
  <properties>
    <maven.compiler.source>17</maven.compiler.source>
    <maven.compiler.target>17</maven.compiler.target>
    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
  </properties>
  <build>
    <plugins>
      <plugin>
        <groupId>org.codehaus.mojo</groupId>
        <artifactId>exec-maven-plugin</artifactId>
        <version>3.1.0</version>
        <configuration>
          <mainClass>com.example.Main</mainClass>
        </configuration>
      </plugin>
    </plugins>
  </build>
</project>
"""

# Fixed test driver - NOT generated by the model. Relies only on getters the
# prompt explicitly requires (not on the model's own equals(), which is a
# separate, related-but-different correctness question) so a bug here can
# only mean the encode/decode round trip itself is wrong, nothing else.
MAIN_JAVA = """package com.example;

import java.util.Arrays;
import java.nio.charset.StandardCharsets;

public class Main {
    public static void main(String[] args) throws Exception {
        byte[] body = "Hello World".getBytes(StandardCharsets.UTF_8);
        Protocol original = new Protocol(1, 2, 1734000000L, body);

        byte[] encoded = ProtocolParser.encode(original);
        Protocol decoded = ProtocolParser.decode(encoded);

        boolean versionOk = decoded.getProtocolVersion() == 1;
        boolean swVersionOk = decoded.getSoftwareVersion() == 2;
        boolean dataLengthOk = decoded.getDataLength() == body.length;
        boolean timeOk = decoded.getTime() == 1734000000L;
        boolean bodyOk = decoded.getBody() != null && Arrays.equals(decoded.getBody(), body);

        System.out.println("[RESULT] protocolVersion=" + decoded.getProtocolVersion()
            + ", softwareVersion=" + decoded.getSoftwareVersion()
            + ", dataLength=" + decoded.getDataLength()
            + ", time=" + decoded.getTime()
            + ", bodyLength=" + (decoded.getBody() == null ? -1 : decoded.getBody().length));

        if (versionOk && swVersionOk && dataLengthOk && timeOk && bodyOk) {
            System.out.println("[VERIFICATION] PASS");
        } else {
            System.out.println("[VERIFICATION] FAIL: versionOk=" + versionOk
                + " swVersionOk=" + swVersionOk + " dataLengthOk=" + dataLengthOk
                + " (expected " + body.length + ", got " + decoded.getDataLength() + ")"
                + " timeOk=" + timeOk + " bodyOk=" + bodyOk);
        }
    }
}
"""


def build_prompt(width_bytes: int) -> str:
    max_value = 2 ** (width_bytes * 8) - 1
    return f"""Write two Java classes for a small binary protocol library: `Protocol` and `ProtocolParser`. This is one isolated layer of a larger system, but for this task you only need these two classes - no Ignite, no Qpid, no Maven setup (that is already provided separately).

Package: com.example

Class `Protocol`:
- Fields: protocolVersion (int, 0-255), softwareVersion (int, 0-255), dataLength (int, 0 to {max_value:,} - the body length only), time (long, treated as a 32-bit big-endian seconds-since-epoch value), body (byte[]).
- A constructor with this exact signature: `Protocol(int protocolVersion, int softwareVersion, long time, byte[] body)` - dataLength is derived from body.length, not passed in.
- Public getters: getProtocolVersion(), getSoftwareVersion(), getDataLength(), getTime(), getBody().
- equals(), hashCode(), and toString(). equals() and hashCode() MUST compare/hash body by CONTENT using Arrays.equals(body, other.body) and Arrays.hashCode(body), never by reference.

Class `ProtocolParser`:
- `static byte[] encode(Protocol protocol)` implementing this EXACT wire format: a header of protocolVersion (1 byte) + softwareVersion (1 byte) + dataLength ({width_bytes} bytes, big-endian) + time (4 bytes, big-endian), followed immediately by the raw body bytes. encode() must auto-calculate dataLength from body.length and use that computed value - never trust or read whatever value might already be stored in the Protocol object's own dataLength field.
- `static Protocol decode(byte[] data)` that parses the header, validates data.length == header_size + dataLength, extracts the body, and throws IllegalArgumentException on malformed input.

Respond with ONLY the two Java files. For each file, put its exact relative path on its own line starting with '### ', immediately followed by a fenced code block containing that file's complete content. Do not include any other files, explanation, or commentary outside the code blocks. Example format:

### Protocol.java
```java
... complete file content ...
```

### ProtocolParser.java
```java
... complete file content ...
```
"""


FILE_BLOCK_RE = re.compile(r"^###\s*(\S+)\s*\n```(?:java)?\n(.*?)```", re.MULTILINE | re.DOTALL)


def extract_files(response: str) -> dict:
    return {m.group(1).strip(): m.group(2) for m in FILE_BLOCK_RE.finditer(response)}


async def run_trial(llm: LLMClient, width_bytes: int, workdir_base: Path, trial_key: str) -> dict:
    prompt = build_prompt(width_bytes)
    start = time.monotonic()
    try:
        response = await llm.complete(
            SYSTEM_PROMPT, prompt,
            model_override=MODEL, base_url_override=BASE_URL, api_key_override="local-key",
            temperature_override=TEMPERATURE,
        )
    except Exception as e:
        return {"outcome": "LLM_ERROR", "elapsed": time.monotonic() - start, "detail": str(e)[:200]}
    elapsed = time.monotonic() - start

    files = extract_files(response)
    if "Protocol.java" not in files or "ProtocolParser.java" not in files:
        return {"outcome": "MISSING_FILES", "elapsed": elapsed, "detail": f"got: {list(files.keys())}"}

    trial_dir = workdir_base / f"trial_{trial_key}"
    src_dir = trial_dir / "src" / "main" / "java" / "com" / "example"
    src_dir.mkdir(parents=True, exist_ok=True)
    (trial_dir / "pom.xml").write_text(POM_XML)
    (src_dir / "Main.java").write_text(MAIN_JAVA)
    (src_dir / "Protocol.java").write_text(files["Protocol.java"])
    (src_dir / "ProtocolParser.java").write_text(files["ProtocolParser.java"])

    try:
        result = subprocess.run(
            ["mvn", "-q", "-DskipTests", "compile", "exec:java"],
            cwd=trial_dir, capture_output=True, text=True, timeout=MVN_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired:
        return {"outcome": "MVN_TIMEOUT", "elapsed": elapsed, "detail": f"exceeded {MVN_TIMEOUT_SECONDS}s"}

    output = result.stdout + result.stderr
    if "[VERIFICATION] PASS" in output:
        return {"outcome": "PASS", "elapsed": elapsed, "detail": ""}
    if "[VERIFICATION] FAIL" in output:
        fail_line = next((l for l in output.splitlines() if "[VERIFICATION] FAIL" in l), "")
        return {"outcome": "ROUNDTRIP_FAIL", "elapsed": elapsed, "detail": fail_line}
    if result.returncode != 0:
        error_lines = [l for l in output.splitlines() if "[ERROR]" in l][:5]
        return {"outcome": "COMPILE_OR_RUNTIME_ERROR", "elapsed": elapsed, "detail": "; ".join(error_lines) or output[-400:]}
    return {"outcome": "UNKNOWN", "elapsed": elapsed, "detail": output[-300:]}


async def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--trials", type=int, default=5)
    parser.add_argument("--widths", type=int, nargs="+", default=[3, 5])
    args = parser.parse_args()

    if shutil.which("mvn") is None:
        print("ERROR: 'mvn' not found on PATH - this POC compiles and runs real Java code.")
        sys.exit(1)

    config = load_config()
    llm = LLMClient(config)

    # Persistent, not tempfile.TemporaryDirectory() - that auto-deletes on exit,
    # which silently threw away every generated Protocol.java/ProtocolParser.java
    # the moment the script finished, with no way to go back and read what the
    # model actually wrote. runs/ follows the same gitignored-output convention
    # as spikes/eval_harness/runs/ and spikes/fix_alignment/runs/ - one
    # timestamped subfolder per invocation so successive runs never overwrite
    # each other's generated code.
    batch_id = time.strftime("%Y%m%d-%H%M%S")
    workdir_base = Path(__file__).resolve().parent / "runs" / batch_id
    workdir_base.mkdir(parents=True, exist_ok=True)
    print(f"Generated files for this run will be kept under: {workdir_base}")

    results: dict = {}
    for width in args.widths:
        print(f"\n{'=' * 78}\ndataLength field width = {width} bytes\n{'=' * 78}")
        trial_results = []
        for i in range(args.trials):
            r = await run_trial(llm, width, workdir_base, f"{width}_{i}")
            trial_results.append(r)
            print(f"  [{i + 1}/{args.trials}] {r['outcome']:<24} {r['elapsed']:6.1f}s   {r['detail'][:120]}")
        results[width] = trial_results

    print(f"\n{'=' * 78}\nSummary\n{'=' * 78}")
    for width, trial_results in results.items():
        outcomes = [r["outcome"] for r in trial_results]
        pass_count = outcomes.count("PASS")
        print(f"  width={width} bytes: {pass_count}/{len(outcomes)} PASS   {outcomes}")


if __name__ == "__main__":
    asyncio.run(main())
