TEST_PREFIXES = ("TEST-", "KERNEL-GOLDEN", "KERNEL-RUNTIME-TRACE", "KERNEL-TESTS", "CERT-DEMO", "CERT-CI",
                 "UI-SCALE", "DEMO-V2-FIXED", "TOOLS-COMMAND-TEST", "WAVE8-S7", "WAVE8-TRACKED", "FINDER-ALIAS")


def row_class(rid: str) -> str:
    if rid.startswith(TEST_PREFIXES):
        return "TEST-HARNESS"
    if rid.startswith("GUI-") or rid.startswith(("HISTORY-", "TECHNICAL-", "APPLICATION-OUTPUT", "RUNTIME-LINE")):
        return "DESKTOP/UI"
    if rid.startswith("PLAT-"):
        return "PLATFORM"
    if rid.startswith(("PRODUCT-", "DEMO-TIME", "REVIEWER-OUTPUT")):
        return "PERFORMANCE"
    return "KERNEL"


def cell(text: str, limit: int = 0) -> str:
    text = " ".join((text or "").split()).replace("|", "\\|")
    if limit and len(text) > limit:
        text = text[: limit - 3] + "..."
    return text or "-"


def main() -> int:
    root = Path(sys.argv[1])
    overrides = json.loads(Path(sys.argv[2]).read_text()) if len(sys.argv) > 2 else {}
    rows = [r for r in csv.DictReader((root / "handover/BACKLOG_REGISTRY.csv").open())
            if not r["status"].upper().startswith("CLOSED")]
    assign = {}
    for sl, ids in SLICES.items():
        for rid in ids.split():
            if rid in assign:
                raise SystemExit(f"assigned twice: {rid}")
            assign[rid] = sl
    ids = [r["id"] for r in rows]
    missing = [i for i in ids if i not in assign]
    absent = [i for i in assign if i not in ids]
    bad_over = [i for i in overrides if i not in ids]
    if missing or absent or bad_over:
        raise SystemExit(f"unassigned={missing} absent={absent} bad_overrides={bad_over}")
    status_of = {i: overrides.get(i, {}).get("reconciliation", "PENDING") for i in ids}
    done = sum(1 for s in status_of.values() if s in ("RECONCILED", "STALE_BOOKKEEPING", "DUPLICATE/SUPERSEDED"))
    needs = sum(1 for s in status_of.values() if s == "NEEDS_CHARACTERIZATION")
    by_slice = {s: sum(1 for i in ids if assign[i] == s) for s in SLICES}
    out = [
        "# Registry coverage index (architecture closure)",
        "",
        f"Canonical runtime baseline described: commit `{BASELINE}`, tree `97a3da6b2ef664e2b7e25c4c6fe3fc3f42f253a0`.",
        "",
        "Generated from `handover/BACKLOG_REGISTRY.csv` at that commit (read-only; the registry is evidence being",
        "reconciled and is not edited during Phase A). One row per non-closed registry row.",
        "",
        f"- Non-closed rows: **{len(rows)}** (MEASURED by this generator; the opening inventory was 141).",
        f"- Reconciled so far: **{done} / {len(rows)}**. Marked `NEEDS_CHARACTERIZATION`: **{needs}**. The rest are `PENDING`.",
        "- Per slice: " + ", ".join(f"{s} {n}" for s, n in by_slice.items()) + ".",
        "",
        "Column meanings:",
        "",
        "- **Registry**: priority / status / blocking flag exactly as the registry states them.",
        "- **Slice / class**: the Phase-A slice that reconciles the row, and whether it concerns the kernel, the test",
        "  harness, the desktop/UI, platform portability or performance.",
        "- **Evidence source**: the registry's own `discovered_in` field.",
        "- **Reconciliation**: `PENDING` (slice not yet run), `RECONCILED`, `NEEDS_CHARACTERIZATION` (interim only),",
        "  `STALE_BOOKKEEPING`, `DUPLICATE/SUPERSEDED`.",
        "- **Disposition**: the eventual architecture disposition (`FIX_REQUIRED_BEFORE_PRODUCTION`,",
        "  `DISPROVED_WITH_EVIDENCE`, `INTENTIONAL_CURRENT_CONTRACT`, `GENUINE_FUTURE_FEATURE`), or `-` while open.",
        "  A disposition written here is a Phase-A proposal for the owner's Phase-D review, not a registry change.",
        "",
        "| # | Row ID | Registry (priority / status / blocking) | Slice / class | Evidence source | Reconciliation | Disposition | Notes, duplicates, supersession |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for n, r in enumerate(rows, 1):
        o = overrides.get(r["id"], {})
        out.append("| {} | `{}` | {} / {} / {} | {} / {} | {} | {} | {} | {} |".format(
            n, r["id"], cell(r["priority"]), cell(r["status"], 40), cell(r["blocking"], 60),
            assign[r["id"]], row_class(r["id"]), cell(r["discovered_in"], 90),
            o.get("reconciliation", "PENDING"), o.get("disposition", "-"), cell(o.get("notes", ""))))
    out.append("")
    (root / "docs/architecture/REGISTRY-COVERAGE.md").write_text("\n".join(out))
    print(f"rows={len(rows)} reconciled={done} per_slice={by_slice}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
