def _digest16(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def _passing_gate(tree, _call):
    """Every verifier of this scene passes its gate: the semantic review, not the gate, is what rules V0 out (run 11's shape)."""
    if not (tree / TEST).exists():
        return {"success": True, "output": "no tests ran"}
    return {"success": True, "output": f"{TEST} .\n1 passed in 0.01s", "test_execution": _report("passed")}


def _scene(tmp_path, *, regenerated, semantic):
    """The scripted enforce run: V0 passes and is ruled invalid; the regeneration answer is ``regenerated`` with run 11's exact analysis prose."""
    real_sentinel = harness.sentinel

    def sentinel(path, *, analysis="", **kwargs):
        if kwargs.get("content") in (P1, P_KEPT):
            analysis = RUN11_ANALYSIS.rstrip("\n")
        return real_sentinel(path, analysis=analysis, **kwargs)

    with patch.object(harness, "sentinel", new=sentinel):
        return _run(tmp_path, semantic=semantic, gate=_passing_gate, model=lambda request: P0 if MARKER not in request["user"] else regenerated)


def _mismatches(scene):
    return [outcome for outcome in scene.result.gate_outcomes if outcome.get("type") == "diagnosis_mismatch"]


def _unit(regenerating=None, pending=None):
    unit = vs.UnitSemantics(ledger=vs.VerifierSemanticLedger(), run_id="r", plan_hash="p", unit_id="s6", goal="g", regenerable=True)
    unit.regenerating, unit.pending = regenerating, pending
    return unit


def _bypass(tmp_path, filepath, *, unit, signature=RUN11_SEMANTIC_FAILURE, vetoed=()):
    from test_workflow import _minimal_attempt_ctx  # noqa: PLC0415

    state = GenerationState()
    state.budgets.last_failure_signature = signature
    for path in vetoed:
        state.budgets.diagnosis_mismatch_veto_counts[path] = 1
    ctx = _minimal_attempt_ctx(tmp_path)
    ctx.verifier_semantic = unit
    return _diagnosis_mismatch_bypass_reason(state, ctx, filepath, RUN11_REGENERATED_VERIFIER)


