def test_run11_sequence_the_regenerated_verifier_reaches_its_test_gate_and_the_second_review(tmp_path):
    scene, seen = _scene(tmp_path, regenerated=P1, semantic=[_invalid(RUN11_RATIONALE), "expectation_valid"])
    result = scene.stop()
    assert result.get("quality_gates_passed") is True, (result.get("failure_category"), result.get("environment_failure"))
    assert scene.applied() == {LIB: LIB_20, TEST: P1}
    assert _mismatches(scene) == [], "the prose heuristic vetoed nothing"
    assert [tree for tree in scene.gate_trees if tree[TEST] == P1], "the regenerated verifier was executed by the test gate"
    assert all(tree[LIB] == LIB_20 for tree in scene.gate_trees if tree[TEST] == P1), "beside the kept production candidate"
    assert [s.verifier_files[0][1] for s in scene.subjects] == [_sha(P0), _sha(P1)], "the person reviewed the regenerated bytes"
    assert seen["takes"] == 1 and [record["during"][0] for record in scene.scopes].count([TEST]) == 1, "still exactly one regeneration"


def test_run11_symptom_without_the_bypass_the_same_answer_is_vetoed_and_the_regeneration_is_spent(tmp_path):
    """The original symptom, and the proof that the scene above really goes through the heuristic: with the in-flight fact withheld from the
    bypass the same answer is refused before any gate. (The request owner asks ``regeneration_in_flight`` only when it has no request to
    send, which does not happen here.)"""
    with patch.object(vs.UnitSemantics, "regeneration_in_flight", new=lambda self, targets: False):
        scene, seen = _scene(tmp_path, regenerated=P1, semantic=[_invalid(RUN11_RATIONALE), "expectation_valid"])
    result = scene.stop()
    assert result.get("quality_gates_passed") is not True
    assert vs.REASON_REGENERATION_NOT_EXECUTED in str(result.get("environment_failure")), result.get("environment_failure")
    (mismatch,) = _mismatches(scene)
    assert "`assertEquals`" in mismatch["output"] and "still appears" in mismatch["output"]
    assert not [tree for tree in scene.gate_trees if tree[TEST] == P1], "no gate ever executed the regenerated verifier"
    assert len(scene.subjects) == 1 and seen["takes"] == 1 and scene.applied() == {LIB: None, TEST: None}


def test_a_regenerated_verifier_that_keeps_the_invalid_expectation_is_still_judged_by_the_gate_and_the_person(tmp_path):
    """No alternate acceptance path: the bypass only lets the candidate reach its authorities. The person rules it invalid again, there is no
    second regeneration, and nothing is applied."""
    scene, seen = _scene(tmp_path, regenerated=P_KEPT, semantic=[_invalid(RUN11_RATIONALE), _invalid("the whole-object assertion is still there")])
    result = scene.stop()
    assert result.get("quality_gates_passed") is not True and scene.applied() == {LIB: None, TEST: None}
    assert result.get("failure_category") == "verifier_semantic_authority_required", result.get("failure_category")
    assert _mismatches(scene) == []
    assert [tree for tree in scene.gate_trees if tree[TEST] == P_KEPT], "the test gate executed it"
    assert [s.verifier_files[0][1] for s in scene.subjects] == [_sha(P0), _sha(P_KEPT)], "and the person judged exactly those bytes"
    assert seen["takes"] == 1 and len([r for r in seen["requests"] if MARKER in r["user"]]) == 1, "one regeneration, never a second"
