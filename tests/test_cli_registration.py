"""The `kriya` command tree is registered unchanged (full modularization E14, SLICE-PLAN E14 "tests").

E14 moves command groups out of ``kriya/cli.py`` into ``kriya/cli_commands/`` and registers them on ``main``. This
snapshot pins, for every command and group reachable from ``main`` (hidden ones included), its name, help, short help,
hidden/deprecated flags and every parameter (name, option strings, type, required, default, multiple, flag, count,
nargs, envvar, help, hidden) - Click's own ``to_info_dict`` of the whole tree, compared structurally (never rendered
``--help`` text, which wraps by terminal width). The golden ``tests/golden/cli_registration/help_tree.json`` was
produced from the BASE bytes (8e0c90a, a ``git archive`` copy at another path) BEFORE any move and is never
regenerated by E14: a moved group that drops, renames or changes a command or an option fails here.

The tree's callbacks (which module a command body lives in) are deliberately NOT part of the snapshot: that is
exactly what E14 changes.
"""
import copy
import inspect
import json
import os
from pathlib import Path
from typing import Any, Dict, Iterator, Tuple

import click

GOLDEN = Path(__file__).resolve().parent / "golden" / "cli_registration" / "help_tree.json"


def help_tree() -> Dict[str, Any]:
    from kriya.cli import main

    with click.Context(main, info_name="kriya") as ctx:
        return json.loads(json.dumps(main.to_info_dict(ctx), sort_keys=True))


def _commands(info: Dict[str, Any], path: Tuple[str, ...] = ()) -> Iterator[Tuple[Tuple[str, ...], Dict[str, Any]]]:
    yield path, info
    for name, child in sorted((info.get("commands") or {}).items()):
        yield from _commands(child, path + (name,))


_HELP_KEYS = ("help", "short_help", "epilog")


def _clean(value: Any) -> Any:
    """Docstring-derived help compared without its indentation: Python 3.13+ dedents a compiled docstring and 3.10-3.12 keep the source indentation, so the same words
    were rendered as two different strings (HOSTED-GOLDEN-DOCSTRING-INDENT-001: the golden came from 3.14, the hosted certification runs 3.12 - 43 command paths differed
    by whitespace only). The words, their order and every other field are still compared exactly."""
    if isinstance(value, dict):
        return {k: (inspect.cleandoc(v) if k in _HELP_KEYS and isinstance(v, str) else _clean(v)) for k, v in value.items()}
    if isinstance(value, list):
        return [_clean(item) for item in value]
    return value


def _mismatches(tree: Dict[str, Any], golden: Dict[str, Any]) -> list:
    """Every command path whose own entry differs from the golden (a missing or extra command included)."""
    ours, theirs = dict(_commands(_clean(tree))), dict(_commands(_clean(golden)))
    strip = lambda info: {k: v for k, v in info.items() if k != "commands"}  # noqa: E731 - the children are compared one by one
    return sorted(" ".join(("kriya",) + path) for path in set(ours) | set(theirs)
                  if path not in ours or path not in theirs or strip(ours[path]) != strip(theirs[path]))


def test_every_command_is_registered_with_its_name_help_and_options():
    assert _mismatches(help_tree(), json.loads(GOLDEN.read_text(encoding="utf-8"))) == []


def test_the_snapshot_is_independent_of_the_checkout_and_the_home():
    # a default derived from the current directory or the home directory would make the golden machine-specific
    text = GOLDEN.read_text(encoding="utf-8")
    for root in {os.getcwd(), str(Path.home()), str(Path(__file__).resolve().parent.parent)}:
        assert root not in text


def test_the_comparison_fails_on_a_dropped_command_or_a_renamed_option():
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    dropped = copy.deepcopy(golden)
    del dropped["commands"]["runs"]["commands"]["prune"]
    renamed = copy.deepcopy(golden)
    option = next(p for p in renamed["commands"]["authority"]["commands"]["approve"]["params"] if p["name"] == "out")
    option["opts"] = ["--output"]
    assert _mismatches(dropped, golden) == ["kriya runs prune"]
    assert _mismatches(renamed, golden) == ["kriya authority approve"]
    assert _mismatches(golden, golden) == []


def test_help_text_is_compared_without_docstring_indentation_but_not_without_its_words():
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    original = golden["commands"]["authority"]["commands"]["approve"]["help"]
    assert "\n" in original
    indented, reworded = copy.deepcopy(golden), copy.deepcopy(golden)
    indented["commands"]["authority"]["commands"]["approve"]["help"] = original.replace("\n", "\n    ")        # the Python 3.10-3.12 rendering of the same docstring
    reworded["commands"]["authority"]["commands"]["approve"]["help"] = original + " Extra words."
    assert _mismatches(indented, golden) == []
    assert _mismatches(reworded, golden) == ["kriya authority approve"]
